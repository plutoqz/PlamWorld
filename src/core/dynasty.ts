import type { MultiPolygon, Polygon } from 'geojson';

// ---- 类型 ----

export interface DynastyDef {
  id: string;
  name: string;
  nameZh: string;
  /** 公元年份（取代表性年份） */
  year: number;
  /** 起止年份 */
  yearRange: [number, number];
  /** 朝代特色色 */
  color: string;
  /** 疆域边界 */
  geometry: Polygon | MultiPolygon;
  /** 简要描述 */
  description: string;
}

