// ---- 类型 ----

export interface DynastyCapital {
  name: string;
  nameZh: string;
  coord: [number, number]; // [lng, lat]
  role: string;           // 如 "首都" | "陪都" | "行在"
  note?: string;
}

export interface DynastyDef {
  id: string;
  name: string;
  nameZh: string;
  /** 公元年份（取代表性鼎盛年份） */
  year: number;
  /** 起止年份 */
  yearRange: [number, number];
  /** 朝代特色色 */
  color: string;
  /** 疆域边界 */
  geometry: Polygon | MultiPolygon;
  /** 历代都城与核心城邑 */
  capitals: DynastyCapital[];
  /** 极盛疆域概述与管辖机构 */
  extentDesc: string;
  /** 简要描述 */
  description: string;
}

